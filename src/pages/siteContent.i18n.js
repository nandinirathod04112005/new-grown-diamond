const TRANSLATIONS = { hi: HI, gu: GU };

/**
 * An editorial page in the visitor's language.
 *
 * `page` is whatever App.jsx handed over for `path` — including the copy with
 * its sections emptied for /shapes and /about, which stays empty. English, an
 * unknown path or an unknown language returns `page` untouched.
 */
export function localizePage(path, page, locale) {
  const over = TRANSLATIONS[locale]?.pages[path];
  return over ? pickCopy({ en: page, [locale]: over }, locale) : page;
}

/** FAQS, as [question, answer] pairs, in the visitor's language. */
export function localizeFaqs(locale) {
  /* English is returned as it stands. Building { en: FAQS, [locale]: … } for
     locale 'en' made the second key overwrite the first with undefined, and
     the English FAQ page rendered blank (TypeError: faqs.map). */
  const faqs = TRANSLATIONS[locale]?.faqs;
  if (locale === 'en' || !faqs) return FAQS;
  return pickCopy({ en: FAQS, [locale]: faqs }, locale);
}

/**
 * EDUCATION_TOPICS in the visitor's language. `href` is untouched; the label
 * comes from the dictionary the header also reads, the blurb from here.
 */
export function localizeTopics(locale) {
  const over = TRANSLATIONS[locale];
  if (!over) return EDUCATION_TOPICS;
  return EDUCATION_TOPICS.map((topic) => ({
    ...topic,
    label: lookup(over.dict, topicKey(topic.href)) ?? topic.label,
    blurb: over.blurbs[topic.href] ?? topic.blurb,
  }));
}
